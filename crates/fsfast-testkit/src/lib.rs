//! Backend conformance suite for fsfast filesystems.
//!
//! Every backend runs this suite in an integration test:
//!
//! ```no_run
//! # async fn demo(fs: std::sync::Arc<dyn fsfast_core::FileSystem>) {
//! use fsfast_testkit::{SuiteConfig, assert_suite};
//! assert_suite(fs, "/scratch/prefix", SuiteConfig::default()).await;
//! # }
//! ```
//!
//! * `root` is a scratch directory (or key prefix) the suite may create
//!   anything under. It must be given in the backend's canonical path form
//!   (what `info()` reports as `name`), because the suite checks that
//!   `info(p).name == normalize(p)`. Each run works in a fresh, uniquely named
//!   sub-directory `root/fsfast-testkit-<unique>`, so concurrent runs against
//!   one root (or one shared store) do not interfere, and removes it at the
//!   end.
//! * Every check is a named async function running in its own sub-directory
//!   `root/fsfast-testkit-<unique>/<check-name>`, which is removed right after
//!   the check. A failing, panicking or timed-out check is recorded and the
//!   suite moves on.
//! * Expectations are capability driven: [`fsfast_core::Capabilities`] decides
//!   whether directories are real (`hierarchical`) or emulated from prefixes,
//!   and whether append / conditional create are exercised or skipped.
//! * Data is generated by a deterministic, random-access pattern seeded by the
//!   file path ([`pattern`]), and mismatches are reported with the absolute
//!   file offset of the first wrong byte.
//!
//! The suite needs a tokio runtime with the time driver enabled (as
//! `#[tokio::test]` provides).

/// Fail the current check with a formatted message.
macro_rules! fail {
    ($($arg:tt)*) => {
        return Err($crate::ctx::CheckError::Failed(format!($($arg)*)))
    };
}

/// Skip the current check with a formatted reason.
macro_rules! skip {
    ($($arg:tt)*) => {
        return Err($crate::ctx::CheckError::Skipped(format!($($arg)*)))
    };
}

/// Fail the current check unless `cond` holds.
macro_rules! ensure {
    ($cond:expr, $($arg:tt)*) => {
        if !$cond {
            fail!($($arg)*);
        }
    };
}

/// Fail the current check unless `actual == expected`.
macro_rules! ensure_eq {
    ($actual:expr, $expected:expr, $($arg:tt)*) => {{
        let (actual, expected) = (&$actual, &$expected);
        if actual != expected {
            fail!(
                "{}: expected {:?}, got {:?}",
                format_args!($($arg)*),
                expected,
                actual
            );
        }
    }};
}

