/// Suite configuration.
#[derive(Debug, Clone)]
pub struct SuiteConfig {
    /// Size of the large patterned file used by `put_get_large` and
    /// `read_ranges_large`. Default 24 MiB.
    pub large_file_bytes: u64,
    /// Names of checks to skip (see [`check_names`]).
    pub skip: BTreeSet<String>,
    /// When non-empty, run only these checks.
    pub only: BTreeSet<String>,
    /// Number of checks run concurrently. Default 1 (sequential, easiest to
    /// debug); remote backends may raise it to shorten wall-clock time.
    pub parallelism: usize,
    /// Per-check timeout. Default 10 minutes.
    pub check_timeout: Duration,
    /// Number of concurrent `read_at` calls in `concurrent_read_at`. Default 32.
    pub concurrent_reads: usize,
    /// Upper bound for the volume written by `open_write_stream`, which
    /// otherwise writes a bit more than `2 × io_hints().request_size`.
    /// Default 64 MiB.
    pub max_stream_bytes: u64,
    /// Local directory for the temporary files of `put_get_large`. Default
    /// [`std::env::temp_dir`].
    pub local_temp_dir: Option<PathBuf>,
    /// Leave everything the suite wrote in place (for debugging).
    pub keep_files: bool,
}

impl Default for SuiteConfig {
    fn default() -> Self {
        SuiteConfig {
            large_file_bytes: 24 << 20,
            skip: BTreeSet::new(),
            only: BTreeSet::new(),
            parallelism: 1,
            check_timeout: Duration::from_secs(600),
            concurrent_reads: 32,
            max_stream_bytes: 64 << 20,
            local_temp_dir: None,
            keep_files: false,
        }
    }
}

impl SuiteConfig {
    /// Add checks to the skip list.
    pub fn skip<I, S>(mut self, names: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        self.skip.extend(names.into_iter().map(Into::into));
        self
    }

    /// Restrict the run to these checks.
    pub fn only<I, S>(mut self, names: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        self.only.extend(names.into_iter().map(Into::into));
        self
    }

    /// Set [`SuiteConfig::large_file_bytes`].
    pub fn large_file_bytes(mut self, n: u64) -> Self {
        self.large_file_bytes = n;
        self
    }

    /// Set [`SuiteConfig::parallelism`].
    pub fn parallelism(mut self, n: usize) -> Self {
        self.parallelism = n.max(1);
        self
    }
}

/// Names of all checks, in execution order.
pub fn check_names() -> Vec<&'static str> {
    checks::REGISTRY.iter().map(|(n, _)| *n).collect()
}

/// Outcome of one check.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CheckStatus {
    Passed,
    /// The message explains what was expected and what happened.
    Failed(String),
    /// The reason the check did not apply (capability, configuration).
    Skipped(String),
}

/// One check's result.
#[derive(Debug, Clone)]
pub struct CheckOutcome {
    pub name: &'static str,
    pub status: CheckStatus,
    pub duration: Duration,
}

/// Result of [`run_suite`].
#[derive(Debug, Clone)]
pub struct SuiteReport {
    /// Canonical protocol of the backend under test.
    pub backend: String,
    /// The run directory the suite worked in.
    pub root: String,
    /// One entry per known check, in execution order.
    pub outcomes: Vec<CheckOutcome>,
    /// Set when the suite could not even start (run directory creation).
    pub setup_error: Option<String>,
    /// Problems removing what the suite wrote.
    pub cleanup_errors: Vec<String>,
    /// Wall-clock time of the whole run.
    pub duration: Duration,
}

impl SuiteReport {
    /// True when no check failed, setup succeeded and cleanup left nothing.
    pub fn is_success(&self) -> bool {
        self.setup_error.is_none() && self.cleanup_errors.is_empty() && self.failed().count() == 0
    }

    /// Checks that passed.
    pub fn passed(&self) -> impl Iterator<Item = &CheckOutcome> {
        self.outcomes
            .iter()
            .filter(|o| o.status == CheckStatus::Passed)
    }

    /// Checks that failed.
    pub fn failed(&self) -> impl Iterator<Item = &CheckOutcome> {
        self.outcomes
            .iter()
            .filter(|o| matches!(o.status, CheckStatus::Failed(_)))
    }

    /// Checks that were skipped.
    pub fn skipped(&self) -> impl Iterator<Item = &CheckOutcome> {
        self.outcomes
            .iter()
            .filter(|o| matches!(o.status, CheckStatus::Skipped(_)))
    }

    /// The outcome of the check called `name`.
    pub fn outcome(&self, name: &str) -> Option<&CheckOutcome> {
        self.outcomes.iter().find(|o| o.name == name)
    }
}

fn write_indented(f: &mut fmt::Formatter<'_>, text: &str, indent: &str) -> fmt::Result {
    for line in text.lines() {
        writeln!(f, "{indent}{line}")?;
    }
    Ok(())
}

impl fmt::Display for SuiteReport {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let verdict = if self.is_success() { "PASSED" } else { "FAILED" };
        writeln!(
            f,
            "fsfast-testkit conformance suite {verdict}: backend `{}`, run directory `{}`",
            self.backend, self.root
        )?;
        writeln!(
            f,
            "  {} passed, {} failed, {} skipped in {:.2?}",
            self.passed().count(),
            self.failed().count(),
            self.skipped().count(),
            self.duration
        )?;
        if let Some(e) = &self.setup_error {
            writeln!(f, "SETUP FAILED:")?;
            write_indented(f, e, "    ")?;
        }
        if self.failed().count() > 0 {
            writeln!(f, "Failed checks:")?;
            for o in self.failed() {
                writeln!(f, "  FAIL {} ({:.2?})", o.name, o.duration)?;
                if let CheckStatus::Failed(m) = &o.status {
                    write_indented(f, m, "      ")?;
                }
            }
        }
        if self.skipped().count() > 0 {
            writeln!(f, "Skipped checks:")?;
            for o in self.skipped() {
                if let CheckStatus::Skipped(m) = &o.status {
                    writeln!(f, "  SKIP {}: {m}", o.name)?;
                }
            }
        }
        if !self.cleanup_errors.is_empty() {
            writeln!(f, "Cleanup problems:")?;
            for e in &self.cleanup_errors {
                write_indented(f, e, "  - ")?;
            }
        }
        Ok(())
    }
}

fn unique_suffix() -> String {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    format!("{}-{nanos:x}-{n}", std::process::id())
}

fn panic_message(p: &(dyn std::any::Any + Send)) -> String {
    if let Some(s) = p.downcast_ref::<&str>() {
        (*s).to_owned()
    } else if let Some(s) = p.downcast_ref::<String>() {
        s.clone()
    } else {
        "non-string panic payload".to_owned()
    }
}

/// Run the conformance suite against `fs` under the scratch prefix `root`.
///
/// Never panics because of a backend failure; inspect the returned report
/// (or use [`assert_suite`]).
pub async fn run_suite(fs: Arc<dyn FileSystem>, root: &str, cfg: SuiteConfig) -> SuiteReport {
    let started = Instant::now();
    let caps = fs.capabilities();
    let hints = fs.io_hints();
    let run_dir = path::join(
        &path::normalize(root),
        &format!("fsfast-testkit-{}", unique_suffix()),
    );
    let mut report = SuiteReport {
        backend: fs.protocols().first().copied().unwrap_or("?").to_owned(),
        root: run_dir.clone(),
        outcomes: Vec::new(),
        setup_error: None,
        cleanup_errors: Vec::new(),
        duration: Duration::ZERO,
    };
    tracing::info!(backend = %report.backend, root = %run_dir, "running fsfast-testkit suite");

    // The highest ancestor of the run directory that does not exist yet: the
    // suite created it (via makedirs) and removes it again at the end.
    let created_from = if caps.hierarchical {
        first_missing_ancestor(fs.as_ref(), &path::normalize(root)).await
    } else {
        None
    };
    if caps.hierarchical
        && let Err(e) = fs.makedirs(&run_dir, true).await
    {
        report.setup_error = Some(format!(
            "makedirs({run_dir:?}, exist_ok=true) failed: {e} [kind: {:?}]",
            e.kind()
        ));
        report.duration = started.elapsed();
        return report;
    }

    let cfg = Arc::new(cfg);
    let mut selected = Vec::new();
    for (idx, (name, f)) in checks::REGISTRY.iter().enumerate() {
        let reason = if cfg.skip.contains(*name) {
            Some("listed in SuiteConfig::skip")
        } else if !cfg.only.is_empty() && !cfg.only.contains(*name) {
            Some("not listed in SuiteConfig::only")
        } else {
            None
        };
        match reason {
            Some(r) => report.outcomes.push(CheckOutcome {
                name,
                status: CheckStatus::Skipped(r.to_owned()),
                duration: Duration::ZERO,
            }),
            None => selected.push((idx, *name, *f)),
        }
    }

    let results: Vec<(usize, CheckOutcome, Vec<String>)> =
        stream::iter(selected.into_iter().map(|(idx, name, f)| {
            let ctx = Ctx {
                fs: fs.clone(),
                dir: path::join(&run_dir, name),
                cfg: cfg.clone(),
                caps,
                hints,
            };
            async move {
                let (outcome, cleanup) = run_check(ctx, name, f).await;
                (idx, outcome, cleanup)
            }
        }))
        .buffer_unordered(cfg.parallelism.max(1))
        .collect()
        .await;

    let mut results = results;
    results.sort_by_key(|(idx, _, _)| *idx);
    for (_, outcome, cleanup) in results {
        report.outcomes.push(outcome);
        report.cleanup_errors.extend(cleanup);
    }
    let order = check_names();
    report.outcomes.sort_by_key(|o| order.iter().position(|n| *n == o.name));

    if !cfg.keep_files {
        let errs = remove_tree(fs.as_ref(), &run_dir, caps.hierarchical).await;
        report
            .cleanup_errors
            .extend(errs.into_iter().map(|e| format!("run directory: {e}")));
        if let Some(top) = created_from {
            remove_created_ancestors(fs.as_ref(), &path::normalize(root), &top).await;
        }
    }
    report.duration = started.elapsed();
    tracing::info!(
        passed = report.passed().count(),
        failed = report.failed().count(),
        skipped = report.skipped().count(),
        "fsfast-testkit suite finished"
    );
    report
}

async fn run_check(ctx: Ctx, name: &'static str, f: checks::CheckFn) -> (CheckOutcome, Vec<String>) {
    let started = Instant::now();
    tracing::debug!(check = name, dir = %ctx.dir, "starting check");
    let status = match ctx.ensure_dir(&ctx.dir).await {
        Err(CheckError::Failed(m) | CheckError::Skipped(m)) => {
            CheckStatus::Failed(format!("setup: {m}"))
        }
        Ok(()) => {
            let fut = AssertUnwindSafe(f(&ctx)).catch_unwind();
            match tokio::time::timeout(ctx.cfg.check_timeout, fut).await {
                Err(_) => CheckStatus::Failed(format!(
                    "timed out after {:?} (SuiteConfig::check_timeout)",
                    ctx.cfg.check_timeout
                )),
                Ok(Err(panic)) => {
                    CheckStatus::Failed(format!("panicked: {}", panic_message(panic.as_ref())))
                }
                Ok(Ok(Ok(()))) => CheckStatus::Passed,
                Ok(Ok(Err(CheckError::Failed(m)))) => CheckStatus::Failed(m),
                Ok(Ok(Err(CheckError::Skipped(m)))) => CheckStatus::Skipped(m),
            }
        }
    };
    let duration = started.elapsed();
    match &status {
        CheckStatus::Failed(m) => tracing::warn!(check = name, "check failed: {m}"),
        _ => tracing::debug!(check = name, ?status, "check finished"),
    }
    let cleanup = if ctx.cfg.keep_files {
        Vec::new()
    } else {
        remove_tree(ctx.fs.as_ref(), &ctx.dir, ctx.caps.hierarchical)
            .await
            .into_iter()
            .map(|e| format!("{name}: {e}"))
            .collect()
    };
    (
        CheckOutcome {
            name,
            status,
            duration,
        },
        cleanup,
    )
}

/// The top-most path among `root` and its ancestors that does not exist.
async fn first_missing_ancestor(fs: &dyn FileSystem, root: &str) -> Option<String> {
    let mut candidates = path::ancestors(root);
    candidates.push(root.to_owned());
    for c in candidates {
        if c.is_empty() || c == "/" {
            continue;
        }
        if let Ok(false) = fs.exists(&c).await {
            return Some(c);
        }
    }
    None
}

/// rmdir `root` and its parents up to `top`, stopping at the first failure
/// (e.g. another run still uses the root). Best effort by design.
async fn remove_created_ancestors(fs: &dyn FileSystem, root: &str, top: &str) {
    let mut d = root.to_owned();
    loop {
        if fs.rmdir(&d).await.is_err() || d == top || d.len() <= top.len() {
            break;
        }
        d = path::parent(&d);
    }
}

/// Remove everything under `dir` (and `dir` itself on hierarchical
/// backends), returning a description of each problem.
async fn remove_tree(fs: &dyn FileSystem, dir: &str, hierarchical: bool) -> Vec<String> {
    let mut errors = Vec::new();
    let entries = match fs
        .find(
            dir,
            &FindOptions {
                maxdepth: None,
                withdirs: true,
            },
        )
        .await
    {
        Ok(v) => v,
        Err(e) => return vec![format!("find({dir:?}) failed: {e}")],
    };
    let files: Vec<String> = entries
        .iter()
        .filter(|e| !e.is_dir())
        .map(|e| e.name.clone())
        .collect();
    for (p, r) in files.iter().zip(fs.rm_files(&files).await) {
        if let Err(e) = r
            && e.kind() != ErrorKind::NotFound
        {
            errors.push(format!("rm_file({p:?}) failed: {e}"));
        }
    }
    let mut dirs: Vec<&str> = entries
        .iter()
        .filter(|e| e.is_dir())
        .map(|e| e.name.as_str())
        .collect();
    let dir_n = path::normalize(dir);
    if hierarchical && !dirs.contains(&dir_n.as_str()) {
        dirs.push(&dir_n);
    }
    // Deepest first.
    dirs.sort_by_key(|d| std::cmp::Reverse(d.matches('/').count()));
    for d in dirs {
        match fs.rmdir(d).await {
            Ok(()) => {}
            Err(e) if e.kind() == ErrorKind::NotFound => {}
            // Emulated directories vanish with their last key; rmdir is
            // backend-specific there, so its errors are not cleanup failures.
            Err(_) if !hierarchical => {}
            Err(e) => errors.push(format!("rmdir({d:?}) failed: {e}")),
        }
    }
    match fs.find(dir, &FindOptions::default()).await {
        Ok(left) if !left.is_empty() => errors.push(format!(
            "{} file(s) left under {dir:?} after cleanup, e.g. {:?}",
            left.len(),
            left[0].name
        )),
        Ok(_) => {}
        Err(e) => errors.push(format!("find({dir:?}) after cleanup failed: {e}")),
    }
    errors
}

/// Run the suite and panic with a readable multi-line report if any check
/// failed (or setup/cleanup failed). Returns the report on success.
pub async fn assert_suite(fs: Arc<dyn FileSystem>, root: &str, cfg: SuiteConfig) -> SuiteReport {
    let report = run_suite(fs, root, cfg).await;
    if !report.is_success() {
        panic!("\n{report}");
    }
    report
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registry_names_are_unique_and_snake_case() {
        let names = check_names();
        let set: BTreeSet<_> = names.iter().collect();
        assert_eq!(set.len(), names.len());
        for n in names {
            assert!(
                n.chars().all(|c| c.is_ascii_lowercase() || c == '_' || c.is_ascii_digit()),
                "{n}"
            );
        }
    }

    #[test]
    fn report_formatting() {
        let report = SuiteReport {
            backend: "memory".into(),
            root: "/r/run".into(),
            outcomes: vec![
                CheckOutcome {
                    name: "a",
                    status: CheckStatus::Passed,
                    duration: Duration::from_millis(1),
                },
                CheckOutcome {
                    name: "b",
                    status: CheckStatus::Failed("line one\nline two".into()),
                    duration: Duration::from_millis(2),
                },
                CheckOutcome {
                    name: "c",
                    status: CheckStatus::Skipped("no append".into()),
                    duration: Duration::ZERO,
                },
            ],
            setup_error: None,
            cleanup_errors: vec!["b: 1 file(s) left".into()],
            duration: Duration::from_millis(5),
        };
        assert!(!report.is_success());
        let s = report.to_string();
        assert!(s.contains("FAILED"), "{s}");
        assert!(s.contains("1 passed, 1 failed, 1 skipped"), "{s}");
        assert!(s.contains("  FAIL b"), "{s}");
        assert!(s.contains("      line one\n      line two"), "{s}");
        assert!(s.contains("SKIP c: no append"), "{s}");
        assert!(s.contains("  - b: 1 file(s) left"), "{s}");
        assert_eq!(report.outcome("c").unwrap().status, CheckStatus::Skipped("no append".into()));
    }

    #[test]
    fn config_builders() {
        let c = SuiteConfig::default()
            .skip(["x", "y"])
            .only(["z"])
            .large_file_bytes(10)
            .parallelism(0);
        assert!(c.skip.contains("x") && c.skip.contains("y"));
        assert!(c.only.contains("z"));
        assert_eq!(c.large_file_bytes, 10);
        assert_eq!(c.parallelism, 1);
    }

    #[test]
    fn unique_suffixes_differ() {
        assert_ne!(unique_suffix(), unique_suffix());
    }
}
