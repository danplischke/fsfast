#!/usr/bin/env python3
"""Generate crates/fsfast-s3/src/params_table.rs from botocore's S3 model.

Run from the repository root:

    .venv/bin/python crates/fsfast-s3/tools/gen_params.py \
        > crates/fsfast-s3/src/params_table.rs

s3fs passes ``s3_additional_kwargs`` (and ``RequestPayer`` for
``requester_pays``) to *every* S3 call, keeping only the parameters the
operation's input shape declares (``ParamKwargsHelper``). The table lists,
for each parameter fsfast forwards, where it goes on the wire (header,
header prefix or query string), its type, and the operations that accept
it, so fsfast filters exactly like s3fs.
"""

import botocore.session

OPS = [
    "ListBuckets", "HeadBucket", "GetBucketLocation", "CreateBucket", "DeleteBucket",
    "ListObjectsV2", "ListObjectVersions", "HeadObject", "GetObject", "PutObject",
    "DeleteObject", "DeleteObjects", "CopyObject", "CreateMultipartUpload", "UploadPart",
    "UploadPartCopy", "CompleteMultipartUpload", "AbortMultipartUpload",
    "GetBucketVersioning", "PutBucketVersioning", "GetObjectTagging", "PutObjectTagging",
    "PutObjectAcl", "PutBucketAcl",
]

# Parameters fsfast sets itself from the operation's arguments (paths,
# ranges, bodies, pagination, conditional requests, checksums it does not
# compute). They are never taken from s3_additional_kwargs.
OWN = {
    "Bucket", "Key", "Body", "ContentLength", "ContentMD5", "Range", "PartNumber",
    "UploadId", "VersionId", "CopySource", "CopySourceRange", "Prefix", "Delimiter",
    "ContinuationToken", "MaxKeys", "EncodingType", "StartAfter", "KeyMarker",
    "VersionIdMarker", "Delete", "MultipartUpload", "CreateBucketConfiguration",
    "IfMatch", "IfNoneMatch", "IfModifiedSince", "IfUnmodifiedSince",
    "CopySourceIfMatch", "CopySourceIfNoneMatch", "CopySourceIfModifiedSince",
    "CopySourceIfUnmodifiedSince", "ChecksumAlgorithm", "ChecksumCRC32",
    "ChecksumCRC32C", "ChecksumCRC64NVME", "ChecksumSHA1", "ChecksumSHA256",
    "ChecksumMode", "ChecksumType", "MpuObjectSize", "WriteOffsetBytes",
    "FetchOwner", "OptionalObjectAttributes", "MaxBuckets", "BucketRegion",
    "IfMatchLastModifiedTime", "IfMatchSize", "IfMatchInitiatedTime",
    # Derived by fsfast (like botocore's sse_md5 handler) from the key.
    "SSECustomerKeyMD5", "CopySourceSSECustomerKeyMD5",
    "BypassGovernanceRetention", "MFA",
}


def main():
    s = botocore.session.get_session()
    model = s.get_service_model("s3")
    params = {}
    for op in OPS:
        shape = model.operation_model(op).input_shape
        if shape is None:
            continue
        for name, m in shape.members.items():
            if name in OWN or name.startswith("Checksum"):
                continue
            loc = m.serialization.get("location")
            if loc not in ("header", "headers", "querystring"):
                continue
            wire = m.serialization.get("name")
            kind = m.type_name
            tsfmt = m.serialization.get("timestampFormat")
            if kind == "timestamp" and tsfmt is None:
                tsfmt = "iso8601" if loc == "querystring" else "rfc822"
            entry = params.setdefault(name, {
                "loc": loc, "wire": wire, "kind": kind, "ts": tsfmt, "ops": [],
            })
            assert (entry["loc"], entry["wire"], entry["kind"]) == (loc, wire, kind), name
            entry["ops"].append(op)

    out = []
    out.append("// @generated by tools/gen_params.py from botocore's S3 service model.")
    out.append("// Do not edit by hand; re-run the generator instead.")
    out.append("")
    out.append("use super::{Loc, Op, ParamKind, ParamSpec};")
    out.append("")
    out.append("/// Every S3 operation fsfast issues, as named in the S3 API.")
    out.append(f"pub(crate) const OPERATIONS: [Op; {len(OPS)}] = [")
    for op in OPS:
        out.append(f"    Op::{op},")
    out.append("];")
    out.append("")
    out.append("/// Forwardable parameters (sorted by name).")
    out.append("pub(crate) static PARAMS: &[ParamSpec] = &[")
    for name in sorted(params):
        e = params[name]
        loc = {"header": "Header", "headers": "HeaderPrefix", "querystring": "Query"}[e["loc"]]
        kind = {
            "string": "ParamKind::String",
            "boolean": "ParamKind::Boolean",
            "integer": "ParamKind::Integer",
            "long": "ParamKind::Integer",
            "map": "ParamKind::Map",
            "timestamp": "ParamKind::Timestamp(%s)" % ("true" if e["ts"] == "iso8601" else "false"),
        }[e["kind"]]
        ops = ", ".join(f"Op::{o}" for o in e["ops"])
        out.append("    ParamSpec {")
        out.append(f"        name: {name!r},".replace("'", '"'))
        out.append(f"        loc: Loc::{loc}({e['wire']!r}),".replace("'", '"'))
        out.append(f"        kind: {kind},")
        out.append(f"        ops: &[{ops}],")
        out.append("    },")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
