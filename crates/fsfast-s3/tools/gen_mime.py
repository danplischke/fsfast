#!/usr/bin/env python3
"""Generate crates/fsfast-s3/src/mime_table.rs from Python's built-in
mimetypes tables (without the system's mime.types files), which s3fs's
put_file uses to guess ContentType.

    .venv/bin/python crates/fsfast-s3/tools/gen_mime.py > crates/fsfast-s3/src/mime_table.rs
"""
import mimetypes

types = dict(mimetypes._types_map_default)
enc = dict(mimetypes._encodings_map_default)
suffix = dict(mimetypes._suffix_map_default)
print("// @generated by tools/gen_mime.py from Python's mimetypes defaults.")
print("// Do not edit by hand.")
print()
print("/// Extension (lower-case, with dot) -> type, sorted by extension.")
print("pub(crate) static TYPES: &[(&str, &str)] = &[")
for k in sorted(types):
    print(f'    ("{k}", "{types[k]}"),')
print("];")
print()
print("/// Compression suffixes (stripped before guessing the type).")
print("pub(crate) static ENCODINGS: &[&str] = &[")
for k in sorted(enc):
    print(f'    "{k}",')
print("];")
print()
print("/// Abbreviated suffixes (`.tgz` -> `.tar.gz`).")
print("pub(crate) static SUFFIXES: &[(&str, &str)] = &[")
for k in sorted(suffix):
    print(f'    ("{k}", "{suffix[k]}"),')
print("];")
