//! AWS Signature Version 4 (header and query-string/presigned forms), with
//! the S3 specifics botocore implements in `S3SigV4Auth` and
//! `S3SigV4QueryAuth`:
//!
//! * The canonical URI is the request path exactly as sent: S3 object keys
//!   are percent-encoded once when the URL is built (see
//!   [`crate::encode::uri_encode`]) and neither normalized nor encoded again.
//! * The canonical query string is the request's (already encoded) query,
//!   split on `&`, each pair split at the first `=` (a missing value is
//!   empty), sorted by encoded name and then value.
//! * Every header present at signing time is signed, except a fixed
//!   blacklist (`user-agent`, `expect`, `transfer-encoding`, ...); `host` is
//!   derived from the URL. Values are trimmed and inner whitespace runs
//!   collapsed. Headers the HTTP client adds later (`user-agent`, `accept`,
//!   `content-length`) are therefore never part of the signature.
//! * The payload hash is the SHA-256 of the body, or `UNSIGNED-PAYLOAD`.
//!
//! The derived signing key is cached per (secret, date, region, service),
//! so steady-state signing costs two SHA-256 digests and one HMAC chain step.
//! Test vectors generated by botocore pin the behaviour
//! (`tests/sigv4_vectors.rs`).

use std::fmt::Write as _;
use std::time::{Duration, SystemTime};

use fsfast_core::{Error, Result};
use fsfast_http_transport::Url;
use fsfast_http_transport::header::{HeaderMap, HeaderName, HeaderValue};
use hmac::{Hmac, KeyInit, Mac};
use parking_lot::Mutex;
use sha2::{Digest, Sha256};

use crate::credentials::Credentials;
use crate::encode::{amz_date, hex_lower, uri_encode};

/// The algorithm name used in the `Authorization` header and presigned URLs.
pub const ALGORITHM: &str = "AWS4-HMAC-SHA256";

/// Payload hash placeholder for bodies that are not signed.
pub const UNSIGNED_PAYLOAD: &str = "UNSIGNED-PAYLOAD";

/// SHA-256 of the empty string.
pub const EMPTY_SHA256: &str = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855";

/// Longest validity of a presigned URL (7 days).
pub const MAX_PRESIGN_EXPIRES: Duration = Duration::from_secs(7 * 24 * 3600);

/// Headers never signed (botocore's `SIGNED_HEADERS_BLACKLIST`): proxies and
/// HTTP clients may add or rewrite them.
const UNSIGNED_HEADERS: &[&str] = &[
    "authorization",
    "baggage",
    "connection",
    "expect",
    "keep-alive",
    "proxy-authenticate",
    "proxy-authorization",
    "te",
    "traceparent",
    "tracestate",
    "trailer",
    "transfer-encoding",
    "upgrade",
    "user-agent",
    "x-amzn-trace-id",
];

type HmacSha256 = Hmac<Sha256>;

fn hmac(key: &[u8], data: &[u8]) -> [u8; 32] {
    let mut m = <HmacSha256 as KeyInit>::new_from_slice(key).expect("HMAC accepts any key length");
    m.update(data);
    m.finalize().into_bytes().into()
}

/// Lower-case hex SHA-256 of `data`.
pub fn sha256_hex(data: &[u8]) -> String {
    hex_lower(&Sha256::digest(data))
}

/// Lower-case hex SHA-256 of several buffers taken as one.
pub fn sha256_hex_chunks<'a>(chunks: impl IntoIterator<Item = &'a [u8]>) -> String {
    let mut h = Sha256::new();
    for c in chunks {
        h.update(c);
    }
    hex_lower(&h.finalize())
}

/// What [`Signer::sign`] computed, for tests and debugging.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SigningOutput {
    /// The canonical request.
    pub canonical_request: String,
    /// The string to sign.
    pub string_to_sign: String,
    /// The hex signature.
    pub signature: String,
    /// The `;`-separated signed header names.
    pub signed_headers: String,
}

#[derive(Debug)]
struct CachedKey {
    secret_digest: [u8; 32],
    date: String,
    region: String,
    key: [u8; 32],
}

/// A SigV4 signer for one service, with a signing-key cache.
#[derive(Debug)]
pub struct Signer {
    service: &'static str,
    cache: Mutex<Option<CachedKey>>,
}

/// The `Host` value of `url`: host plus a non-default port (IPv6 literals
/// keep their brackets), exactly as the HTTP client sends it.
pub fn host_header(url: &Url) -> Result<String> {
    let host = url
        .host_str()
        .ok_or_else(|| Error::invalid_input(format!("URL without host: {url}")))?;
    Ok(match url.port() {
        Some(p) => format!("{host}:{p}"),
        None => host.to_owned(),
    })
}

/// The canonical query string of `url` (see the module docs).
pub fn canonical_query(url: &Url) -> String {
    let Some(q) = url.query().filter(|q| !q.is_empty()) else {
        return String::new();
    };
    let mut pairs: Vec<(&str, &str)> = q
        .split('&')
        .map(|p| p.split_once('=').unwrap_or((p, "")))
        .collect();
    pairs.sort_unstable();
    let mut out = String::with_capacity(q.len() + 8);
    for (i, (k, v)) in pairs.iter().enumerate() {
        if i > 0 {
            out.push('&');
        }
        out.push_str(k);
        out.push('=');
        out.push_str(v);
    }
    out
}

/// Trim and collapse whitespace runs in a header value (bytes outside ASCII
/// are kept as they are).
fn trim_all(v: &[u8], out: &mut Vec<u8>) {
    let mut started = false;
    let mut pending_space = false;
    for &b in v {
        if b == b' ' || b == b'\t' || b == b'\n' || b == b'\r' {
            pending_space = started;
            continue;
        }
        if pending_space {
            out.push(b' ');
        }
        pending_space = false;
        started = true;
        out.push(b);
    }
}

impl Signer {
    /// A signer for `service` (`"s3"`, `"sts"`).
    pub fn new(service: &'static str) -> Self {
        Signer {
            service,
            cache: Mutex::new(None),
        }
    }

    /// The derived signing key for `date` (`YYYYMMDD`) and `region`.
    fn signing_key(&self, creds: &Credentials, date: &str, region: &str) -> [u8; 32] {
        let secret = creds.secret_access_key();
        let digest: [u8; 32] = Sha256::digest(secret.as_bytes()).into();
        {
            let cache = self.cache.lock();
            if let Some(c) = cache.as_ref()
                && c.secret_digest == digest
                && c.date == date
                && c.region == region
            {
                return c.key;
            }
        }
        let mut k = Vec::with_capacity(4 + secret.len());
        k.extend_from_slice(b"AWS4");
        k.extend_from_slice(secret.as_bytes());
        let k_date = hmac(&k, date.as_bytes());
        zeroize::Zeroize::zeroize(&mut k);
        let k_region = hmac(&k_date, region.as_bytes());
        let k_service = hmac(&k_region, self.service.as_bytes());
        let key = hmac(&k_service, b"aws4_request");
        *self.cache.lock() = Some(CachedKey {
            secret_digest: digest,
            date: date.to_owned(),
            region: region.to_owned(),
            key,
        });
        key
    }

    fn scope(&self, date: &str, region: &str) -> String {
        format!("{date}/{region}/{}/aws4_request", self.service)
    }

    /// Sign a request in place: sets `x-amz-date`, `x-amz-content-sha256`
    /// (S3 only), `x-amz-security-token` (temporary credentials) and
    /// `authorization` in `headers`.
    ///
    /// `payload_hash` is the hex SHA-256 of the body or
    /// [`UNSIGNED_PAYLOAD`].
    pub fn sign(
        &self,
        method: &str,
        url: &Url,
        headers: &mut HeaderMap,
        payload_hash: &str,
        creds: &Credentials,
        region: &str,
        now: SystemTime,
    ) -> Result<SigningOutput> {
        let timestamp = amz_date(now);
        let date = &timestamp[..8];
        let hv = |s: &str| {
            HeaderValue::from_str(s)
                .map_err(|_| Error::invalid_input("credential or hash contains invalid characters"))
        };
        headers.remove(fsfast_http_transport::header::AUTHORIZATION);
        headers.insert(HeaderName::from_static("x-amz-date"), hv(&timestamp)?);
        if self.service == "s3" {
            headers.insert(
                HeaderName::from_static("x-amz-content-sha256"),
                hv(payload_hash)?,
            );
        }
        match creds.session_token() {
            Some(t) => {
                let mut v = hv(t)?;
                v.set_sensitive(true);
                headers.insert(HeaderName::from_static("x-amz-security-token"), v);
            }
            None => {
                headers.remove("x-amz-security-token");
            }
        }

        let host = host_header(url)?;
        // Canonical headers: (name, trimmed value) sorted by name; repeated
        // names are joined with ','.
        let mut names: Vec<&str> = headers
            .keys()
            .map(HeaderName::as_str)
            .filter(|n| !UNSIGNED_HEADERS.contains(n) && *n != "host")
            .collect();
        names.push("host");
        names.sort_unstable();
        names.dedup();

        let mut cr: Vec<u8> = Vec::with_capacity(512);
        cr.extend_from_slice(method.as_bytes());
        cr.push(b'\n');
        cr.extend_from_slice(url.path().as_bytes());
        cr.push(b'\n');
        cr.extend_from_slice(canonical_query(url).as_bytes());
        cr.push(b'\n');
        for name in &names {
            cr.extend_from_slice(name.as_bytes());
            cr.push(b':');
            if *name == "host" {
                cr.extend_from_slice(host.as_bytes());
            } else {
                for (i, v) in headers.get_all(*name).iter().enumerate() {
                    if i > 0 {
                        cr.push(b',');
                    }
                    trim_all(v.as_bytes(), &mut cr);
                }
            }
            cr.push(b'\n');
        }
        cr.push(b'\n');
        let signed_headers = names.join(";");
        cr.extend_from_slice(signed_headers.as_bytes());
        cr.push(b'\n');
        cr.extend_from_slice(payload_hash.as_bytes());

        let scope = self.scope(date, region);
        let string_to_sign = format!(
            "{ALGORITHM}\n{timestamp}\n{scope}\n{}",
            hex_lower(&Sha256::digest(&cr))
        );
        let key = self.signing_key(creds, date, region);
        let signature = hex_lower(&hmac(&key, string_to_sign.as_bytes()));
        let auth = format!(
            "{ALGORITHM} Credential={}/{scope}, SignedHeaders={signed_headers}, Signature={signature}",
            creds.access_key_id()
        );
        let mut auth = hv(&auth)?;
        auth.set_sensitive(true);
        headers.insert(fsfast_http_transport::header::AUTHORIZATION, auth);
        Ok(SigningOutput {
            canonical_request: String::from_utf8_lossy(&cr).into_owned(),
            string_to_sign,
            signature,
            signed_headers,
        })
    }

    /// Presign `url` for `method` (query-string authentication, `host` the
    /// only signed header, `UNSIGNED-PAYLOAD`), valid for `expires`.
    /// Returns the URL with the `X-Amz-*` parameters and the signature.
    pub fn presign(
        &self,
        method: &str,
        url: &Url,
        creds: &Credentials,
        region: &str,
        now: SystemTime,
        expires: Duration,
    ) -> Result<Url> {
        let timestamp = amz_date(now);
        let date = &timestamp[..8];
        let scope = self.scope(date, region);
        let mut query = url.query().unwrap_or("").to_owned();
        let mut add = |k: &str, v: &str| {
            if !query.is_empty() {
                query.push('&');
            }
            query.push_str(k);
            query.push('=');
            query.push_str(&uri_encode(v, false));
        };
        add("X-Amz-Algorithm", ALGORITHM);
        add(
            "X-Amz-Credential",
            &format!("{}/{scope}", creds.access_key_id()),
        );
        add("X-Amz-Date", &timestamp);
        add("X-Amz-Expires", &expires.as_secs().to_string());
        add("X-Amz-SignedHeaders", "host");
        if let Some(t) = creds.session_token() {
            add("X-Amz-Security-Token", t);
        }
        let mut out = url.clone();
        out.set_query(Some(&query));
        let host = host_header(&out)?;
        let mut cr = String::with_capacity(256 + query.len());
        let _ = write!(
            cr,
            "{method}\n{}\n{}\nhost:{host}\n\nhost\n{UNSIGNED_PAYLOAD}",
            out.path(),
            canonical_query(&out)
        );
        let string_to_sign = format!(
            "{ALGORITHM}\n{timestamp}\n{scope}\n{}",
            sha256_hex(cr.as_bytes())
        );
        let key = self.signing_key(creds, date, region);
        let signature = hex_lower(&hmac(&key, string_to_sign.as_bytes()));
        query.push_str("&X-Amz-Signature=");
        query.push_str(&signature);
        out.set_query(Some(&query));
        Ok(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn creds() -> Credentials {
        Credentials::new(
            "AKIDEXAMPLE",
            "wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY",
            None,
            None,
        )
    }

    #[test]
    fn aws_documentation_example() {
        // The GET Object example from the S3 SigV4 documentation
        // ("Example: GET Object", examplebucket, 2013-05-24).
        let c = Credentials::new(
            "AKIAIOSFODNN7EXAMPLE",
            "wJalrXUtnFEMI/K7MDENG/bPxRfiCYEXAMPLEKEY",
            None,
            None,
        );
        let url = Url::parse("https://examplebucket.s3.amazonaws.com/test.txt").unwrap();
        let mut h = HeaderMap::new();
        h.insert("range", HeaderValue::from_static("bytes=0-9"));
        let t = crate::encode::parse_iso8601("2013-05-24T00:00:00Z").unwrap();
        let out = Signer::new("s3")
            .sign("GET", &url, &mut h, EMPTY_SHA256, &c, "us-east-1", t)
            .unwrap();
        assert_eq!(
            out.signature,
            "f0e8bdb87c964420e857bd35b5d6ed310bd44f0170aba48dd91039c6036bdb41"
        );
    }

    #[test]
    fn presign_documentation_example() {
        // "Example: Presigned URL" from the S3 query-auth documentation.
        let c = Credentials::new(
            "AKIAIOSFODNN7EXAMPLE",
            "wJalrXUtnFEMI/K7MDENG/bPxRfiCYEXAMPLEKEY",
            None,
            None,
        );
        let url = Url::parse("https://examplebucket.s3.amazonaws.com/test.txt").unwrap();
        let t = crate::encode::parse_iso8601("2013-05-24T00:00:00Z").unwrap();
        let out = Signer::new("s3")
            .presign("GET", &url, &c, "us-east-1", t, Duration::from_secs(86400))
            .unwrap();
        assert!(
            out.as_str().ends_with(
                "X-Amz-Signature=aeeed9bbccd4d02ee5c0109b86d86835f995330da4c265957d157751f604d404"
            ),
            "{out}"
        );
    }

    #[test]
    fn canonical_query_sorts_encoded_pairs() {
        let u = Url::parse("http://h/b?prefix=b&list-type=2&a=2&a=1&uploads").unwrap();
        assert_eq!(canonical_query(&u), "a=1&a=2&list-type=2&prefix=b&uploads=");
    }

    #[test]
    fn whitespace_is_collapsed() {
        let mut out = Vec::new();
        trim_all(b"  multiple   spaces\there ", &mut out);
        assert_eq!(out, b"multiple spaces here");
    }

    #[test]
    fn signing_key_cache_is_keyed_by_secret() {
        let s = Signer::new("s3");
        let a = s.signing_key(&creds(), "20261124", "us-east-1");
        let other = Credentials::new("AK", "other", None, None);
        let b = s.signing_key(&other, "20261124", "us-east-1");
        assert_ne!(a, b);
        assert_eq!(s.signing_key(&creds(), "20261124", "us-east-1"), a);
        assert_ne!(s.signing_key(&creds(), "20261125", "us-east-1"), a);
    }
}
