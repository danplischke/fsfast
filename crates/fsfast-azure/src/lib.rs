//! fsfast-azure: an adlfs-compatible Azure Blob Storage filesystem.
//!
//! [`AzureBlobFileSystem`] implements [`fsfast_core::FileSystem`] over the
//! Blob service REST API with the semantics of adlfs's
//! `AzureBlobFileSystem` (protocols `abfs`, `az`, `abfss`):
//!
//! * **Paths** are `container/path/to/blob` ([`path::strip_protocol`]
//!   reproduces adlfs's `_strip_protocol`, including
//!   `abfs://container@account.dfs.core.windows.net/...`), with
//!   `?versionid=` on version-aware filesystems.
//! * **Directories** are emulated from `/`-delimited prefixes; blobs with
//!   `hdi_isfolder=true` / `is_directory=true` metadata (ADLS Gen2 and adlfs
//!   markers) and `name/` blobs count as directories. `info()` keys are
//!   adlfs's ([`info`]); containers are directories at the top level.
//! * **Auth** ([`auth`]): Shared Key (signed here), SAS tokens (given, or
//!   generated by `sign()`), connection strings ([`connstr`]), anonymous
//!   access, and Entra ID tokens (client secret, managed identity, workload
//!   identity, Azure CLI, adlfs's `DefaultAzureCredential` chain).
//! * **Transfers**: reads are ranged GETs pinned to the ETag (or version),
//!   large reads are parallel ([`read`]); writes are Put Blob or parallel Put
//!   Block + Put Block List through [`fsfast_engine::PartUploader`];
//!   `xb` uses `If-None-Match: *`; `ab` appends to append blobs, and to block
//!   blobs by committing a longer block list ([`write`](mod@write)); copies are
//!   server-side Copy Blob.
//!
//! Options follow adlfs's constructor and `AZURE_STORAGE_*` variables (see
//! [`options`]); unknown options are errors.
//!
//! ADLS Gen2: with `hns=True`, `mv_file` is one atomic DFS Path Rename;
//! everything else uses the Blob API, as adlfs does (directories created by
//! the DFS API appear through their `hdi_isfolder` markers). Recursive
//! deletes through the DFS endpoint are not implemented.

