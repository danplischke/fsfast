/// State shared by the filesystem and its handles.
pub(crate) struct Shared {
    pub client: Client,
    pub cfg: AzureConfig,
    pub budget: MemoryBudget,
    pub stats: Arc<Stats>,
    /// Back-reference used by handles that need filesystem operations.
    me: std::sync::Weak<Shared>,
}

impl fmt::Debug for Shared {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Shared")
            .field("endpoint", &self.client.endpoint)
            .field("auth", &self.cfg.auth)
            .finish_non_exhaustive()
    }
}

impl Shared {
    /// A filesystem view of this state.
    pub(crate) fn fs(&self) -> AzureBlobFileSystem {
        AzureBlobFileSystem {
            sh: self
                .me
                .upgrade()
                .expect("shared state is alive while borrowed"),
        }
    }
}

/// adlfs-compatible Azure Blob Storage filesystem.
#[derive(Clone)]
pub struct AzureBlobFileSystem {
    pub(crate) sh: Arc<Shared>,
}

impl fmt::Debug for AzureBlobFileSystem {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("AzureBlobFileSystem")
            .field("endpoint", &self.sh.client.endpoint)
            .field("account", &self.sh.cfg.account_name)
            .field("auth", &self.sh.cfg.auth)
            .finish()
    }
}

/// A source that is known to be unavailable (shown in chain errors).
#[derive(Debug)]
struct Unavailable(&'static str, String);

#[async_trait]
impl TokenSource for Unavailable {
    async fn fetch(&self, _: &TokenHttp) -> Result<AccessToken> {
        Err(Error::permission_denied(self.1.clone()))
    }
    fn name(&self) -> &'static str {
        self.0
    }
}

fn client_secret(sp: &ServicePrincipal) -> ClientSecret {
    ClientSecret {
        tenant_id: sp.tenant_id.clone(),
        client_id: sp.client_id.clone(),
        client_secret: sp.client_secret.clone(),
        authority: sp.authority.clone(),
    }
}

/// Assemble `DefaultAzureCredential`.
pub(crate) fn default_chain(spec: &DefaultChainSpec) -> Chain {
    let mut sources: Vec<Box<dyn TokenSource>> = Vec::new();
    if let Some(sp) = &spec.environment {
        sources.push(Box::new(client_secret(sp)));
    } else if let Some(msg) = &spec.environment_unavailable {
        sources.push(Box::new(Unavailable("EnvironmentCredential", msg.clone())));
    }
    if let Some(w) = &spec.workload {
        sources.push(Box::new(WorkloadIdentity {
            tenant_id: w.tenant_id.clone(),
            client_id: w.client_id.clone(),
            token_file: w.token_file.clone(),
            authority: w.authority.clone(),
        }));
    }
    if let Some(m) = &spec.managed_identity {
        sources.push(Box::new(ManagedIdentity {
            endpoint: m.endpoint.clone(),
            client_id: m.client_id.clone(),
        }));
    }
    if let Some(c) = &spec.cli {
        sources.push(Box::new(AzureCli {
            tenant_id: c.tenant_id.clone(),
            timeout: c.timeout,
            program: "az".to_owned(),
        }));
    }
    Chain::new(sources)
}

/// HTTP clients for token endpoints: Entra ID through the configured proxy;
/// identity endpoints (IMDS, App Service) directly, with short timeouts so
/// an absent IMDS fails fast in the default chain.
fn token_http(base: &HttpConfig) -> Result<TokenHttp> {
    let aad = HttpClient::new(base.clone())?;
    let local = HttpClient::new(HttpConfig {
        connect_timeout: Some(Duration::from_secs(1)),
        total_timeout: Some(Duration::from_secs(10)),
        max_retries: 1,
        proxy: ProxyConfig::Disabled,
        ..base.clone()
    })?;
    Ok(TokenHttp { aad, local })
}

fn credential(spec: &AuthSpec, http: &HttpConfig) -> Result<Credential> {
    let bearer = |src: Box<dyn TokenSource>| -> Result<Credential> {
        Ok(Credential::Bearer(TokenCache::new(src, token_http(http)?)))
    };
    match spec {
        AuthSpec::Anonymous => Ok(Credential::Anonymous),
        AuthSpec::SharedKey { account, key } => Ok(Credential::SharedKey(Arc::new(
            SharedKey::new(account.clone(), key)?,
        ))),
        AuthSpec::Sas(s) => Ok(Credential::Sas(Arc::from(auth::sas::normalize_sas(s)))),
        AuthSpec::StaticToken { token, expires_on } => bearer(Box::new(StaticToken(AccessToken {
            token: token.clone(),
            expires_on: *expires_on,
        }))),
        AuthSpec::ClientSecret(sp) => bearer(Box::new(client_secret(sp))),
        AuthSpec::Default(d) => bearer(Box::new(default_chain(d))),
    }
}

impl AzureBlobFileSystem {
    /// Build from adlfs `storage_options` (environment variables from the
    /// process environment).
    pub fn from_options(opts: Options) -> Result<Self> {
        Self::from_options_with_env(opts, &process_env)
    }

    /// Build from options with an explicit environment lookup (tests).
    pub fn from_options_with_env(opts: Options, env: options::EnvFn<'_>) -> Result<Self> {
        let cfg = AzureConfig::from_options(opts, env)?;
        Self::from_config(cfg)
    }

    /// Build from a parsed configuration.
    pub fn from_config(cfg: AzureConfig) -> Result<Self> {
        let stats = Arc::new(Stats::new());
        let http = HttpClient::builder(cfg.http.clone())
            .stats(stats.clone())
            .error_parser(Arc::new(AzureErrorParser))
            .build()?;
        let cred = credential(&cfg.auth, &cfg.http)?;
        let client = Client {
            http,
            endpoint: cfg.active_endpoint()?,
            cred,
            server_timeout: cfg.server_timeout,
        };
        let sh = Arc::new_cyclic(|me| Shared {
            client,
            cfg,
            budget: MemoryBudget::global().clone(),
            stats,
            me: me.clone(),
        });
        Ok(AzureBlobFileSystem { sh })
    }

    /// The parsed configuration.
    pub fn config(&self) -> &AzureConfig {
        &self.sh.cfg
    }

    /// The blob endpoint requests go to.
    pub fn endpoint(&self) -> &str {
        &self.sh.client.endpoint
    }

    /// The storage account name, when known.
    pub fn account_name(&self) -> Option<&str> {
        self.sh.cfg.account_name.as_deref()
    }

    /// adlfs `blocksize` (default block size of file objects).
    pub fn blocksize(&self) -> usize {
        self.sh.cfg.blocksize
    }

    /// adlfs `default_fill_cache`.
    pub fn default_fill_cache(&self) -> bool {
        self.sh.cfg.default_fill_cache
    }

    /// adlfs `default_cache_type`.
    pub fn default_cache_type(&self) -> &str {
        &self.sh.cfg.default_cache_type
    }

    /// adlfs `version_aware`.
    pub fn version_aware(&self) -> bool {
        self.sh.cfg.version_aware
    }

    /// Request statistics.
    pub fn stats(&self) -> &Arc<Stats> {
        &self.sh.stats
    }

    /// The credential in use.
    pub fn credential(&self) -> &Credential {
        &self.sh.client.cred
    }

    /// adlfs `_strip_protocol`.
    pub fn strip_protocol(path: &str) -> String {
        path::strip_protocol(path)
    }

    /// adlfs `_get_kwargs_from_urls`: `(account_name, version_aware)`.
    pub fn kwargs_from_url(url: &str) -> (Option<String>, bool) {
        path::kwargs_from_url(url)
    }

    /// Open for reading, returning the concrete handle type.
    pub async fn open(&self, path: &str, opts: &ReadOptions) -> Result<AzureReadHandle> {
        self.open_read_impl(path, opts).await
    }

    /// Create a container (adlfs `mkdir` at the top level, without the
    /// existence check).
    pub async fn create_container_raw(&self, container: &str) -> Result<()> {
        self.create_container(container).await
    }

    /// Delete a container and everything in it (adlfs `rmdir(container)`).
    pub async fn delete_container_raw(&self, container: &str) -> Result<()> {
        self.delete_container(container).await
    }

    /// adlfs `setxattrs`: replace the blob's metadata.
    pub async fn set_metadata(
        &self,
        path: &str,
        metadata: &std::collections::BTreeMap<String, String>,
    ) -> Result<()> {
        let p = path::split_path(path, self.sh.cfg.version_aware);
        let full = p.full();
        if p.blob.is_empty() {
            return Err(Error::is_a_directory(full));
        }
        let q = client::Query::new().with("comp", "metadata");
        let mut req = self
            .sh
            .client
            .request(
                fsfast_http_transport::Method::PUT,
                &self.sh.client.blob_url(p.container, p.blob),
                &q,
            )?
            .path(full.clone());
        for (k, v) in metadata {
            let name = fsfast_http_transport::header::HeaderName::from_bytes(
                format!("x-ms-meta-{k}").as_bytes(),
            )
            .map_err(|_| Error::invalid_input(format!("invalid metadata name {k:?}")))?;
            let value = fsfast_http_transport::header::HeaderValue::from_str(v)
                .map_err(|_| Error::invalid_input(format!("invalid metadata value {v:?}")))?;
            req.headers_mut().insert(name, value);
        }
        self.sh.client.send_headers(req).await.map(|_| ())
    }
}

#[async_trait]
impl FileSystem for AzureBlobFileSystem {
    fn protocols(&self) -> &'static [&'static str] {
        PROTOCOLS
    }

    fn capabilities(&self) -> Capabilities {
        Capabilities {
            hierarchical: false,
            atomic_rename: self.sh.cfg.hns,
            server_side_copy: true,
            append: true,
            conditional_create: true,
            random_write: false,
            versioning: self.sh.cfg.version_aware,
            signed_urls: self.sh.cfg.signing_key.is_some(),
            pinned_reads: true,
        }
    }

    fn io_hints(&self) -> IoHints {
        IoHints {
            request_size: self.sh.cfg.request_size,
            max_concurrency: self.sh.cfg.max_concurrency,
            coalesce_gap: 1 << 20,
            max_coalesced: 32 << 20,
        }
    }

    async fn info(&self, path: &str) -> Result<FileInfo> {
        self.info_impl(path).await
    }

    async fn ls(&self, path: &str) -> Result<Vec<FileInfo>> {
        self.ls_impl(path).await
    }

    async fn find(&self, path: &str, opts: &FindOptions) -> Result<Vec<FileInfo>> {
        self.find_impl(path, opts).await
    }

    async fn open_read(&self, path: &str, opts: &ReadOptions) -> Result<Arc<dyn ReadHandle>> {
        Ok(Arc::new(self.open_read_impl(path, opts).await?))
    }

    async fn open_write(&self, path: &str, opts: &WriteOptions) -> Result<Box<dyn WriteHandle>> {
        Ok(Box::new(self.open_write_impl(path, opts).await?))
    }

    async fn cat_file(&self, path: &str, range: ByteRange) -> Result<Bytes> {
        self.cat_file_impl(path, range).await
    }

    async fn pipe_file(&self, path: &str, data: Bytes, opts: &WriteOptions) -> Result<()> {
        if opts.mode == fsfast_core::WriteMode::Append {
            let mut w = self.open_write_impl(path, opts).await?;
            let res = async {
                if !data.is_empty() {
                    w.write(data).await?;
                }
                w.close().await
            }
            .await;
            if res.is_err() {
                let _ = w.abort().await;
            }
            return res;
        }
        self.pipe_file_impl(path, data, opts).await
    }

    async fn rm_file(&self, path: &str) -> Result<()> {
        self.rm_file_impl(path).await
    }

    async fn rm_files(&self, paths: &[String]) -> Vec<Result<()>> {
        self.rm_files_impl(paths).await
    }

    async fn mkdir(&self, path: &str, create_parents: bool) -> Result<()> {
        self.mkdir_impl(path, create_parents).await
    }

    async fn rmdir(&self, path: &str) -> Result<()> {
        self.rmdir_impl(path).await
    }

    async fn cp_file(&self, src: &str, dst: &str) -> Result<()> {
        self.cp_file_impl(src, dst).await
    }

    async fn mv_file(&self, src: &str, dst: &str) -> Result<()> {
        self.mv_file_impl(src, dst).await
    }

    async fn sign(&self, path: &str, expires: Duration) -> Result<String> {
        self.sign_impl(path, expires)
    }
}
